#!/usr/bin/env python3
"""
Rebuilds artifacts/booking/public/llms-full.txt from the live site.

llms.txt is the hand-kept index of the site's public pages. This script fetches every page that index links
to and writes its readable text (headings, paragraphs, list items, table rows) into llms-full.txt, so the
full-text file can never drift from what the pages actually say. Run it after changing marketing pages:

    python3 scripts/gen-llms-full.py && cp artifacts/booking/public/llms-full.txt artifacts/api-server/dist/public/
"""
import re
import sys
import time
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "artifacts/booking/public/llms.txt"
OUT = ROOT / "artifacts/booking/public/llms-full.txt"
SKIP_INSIDE = {"script", "style", "noscript", "svg", "nav", "header", "footer", "form", "button", "select", "iframe"}
HEADINGS = {"h1": "# ", "h2": "## ", "h3": "### ", "h4": "#### "}
BLOCKS = {"p", "li", "tr", "h1", "h2", "h3", "h4", "blockquote", "dt", "dd", "figcaption"}


class Text(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.skip = 0
        self.title = ""
        self.in_title = False
        self.lines = []
        self.buf = []
        self.tag = None

    def flush(self):
        text = re.sub(r"\s+", " ", "".join(self.buf)).strip()
        self.buf = []
        if not text:
            return
        if self.tag in HEADINGS:
            self.lines.append("\n" + HEADINGS[self.tag] + text)
        elif self.tag == "li":
            self.lines.append("- " + text)
        else:
            self.lines.append(text)

    def handle_starttag(self, tag, attrs):
        if tag == "title":
            self.in_title = True
        if tag in SKIP_INSIDE:
            self.skip += 1
        if self.skip:
            return
        if tag in BLOCKS:
            self.flush()
            self.tag = tag
        elif tag in ("td", "th"):
            self.buf.append(" | ")
        else:
            # Links, spans and buttons sit side by side in the markup with no space between them.
            self.buf.append(" ")

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        if tag in SKIP_INSIDE and self.skip:
            self.skip -= 1
            return
        if not self.skip and tag in BLOCKS:
            self.flush()
            self.tag = None

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        elif not self.skip:
            self.buf.append(data)


def page(url):
    req = urllib.request.Request(url, headers={"User-Agent": "certxa-llms-full/1.0 (+https://certxa.com/llms.txt)"})
    with urllib.request.urlopen(req, timeout=30) as res:
        html = res.read().decode("utf-8", "replace")
    parser = Text()
    parser.feed(html)
    parser.flush()
    lines, last = [], None
    for line in parser.lines:
        if line != last:  # the same sentence rendered twice in a row (mobile and desktop copies)
            lines.append(line)
        last = line
    return parser.title.strip(), "\n".join(lines).strip()


def main():
    index = INDEX.read_text(encoding="utf-8")
    urls = []
    for url in re.findall(r"\]\((https://certxa\.com[^)\s]*)\)", index):
        if "llms" in url or "/listings/" in url or url in urls or re.search(r"\.(txt|xml)$", url):
            continue
        urls.append(url)
    # Every published blog post, from the blog's own sitemap.
    try:
        with urllib.request.urlopen("https://certxa.com/blog/sitemap.xml", timeout=30) as res:
            for url in re.findall(r"<loc>(https://certxa\.com/blog/[^<]+)</loc>", res.read().decode("utf-8", "replace")):
                if url not in urls:
                    urls.append(url)
    except Exception as err:
        print(f"skip blog sitemap: {err}", file=sys.stderr)
    parts = [
        "# Certxa — Full Page Content (llms-full.txt)\n",
        "> The complete text of Certxa's public pages, taken from the live site, for AI systems that read whole pages "
        "rather than the summary index at https://certxa.com/llms.txt. Generated by scripts/gen-llms-full.py.\n",
    ]
    failed = []
    for url in urls:
        try:
            title, text = page(url)
        except Exception as err:  # one unreachable page must not empty the file
            failed.append(f"{url}: {err}")
            continue
        if len(text.split()) < 40:
            failed.append(f"{url}: only {len(text.split())} words")
            continue
        parts.append(f"\n---\n\n## {title or url}\nSource: {url}\n\n{text}\n")
        print(f"ok   {url}  ({len(text.split())} words)")
        time.sleep(1)
    if failed:
        print("\n".join("skip " + f for f in failed), file=sys.stderr)
    if len(parts) < 8:
        sys.exit("Too few pages could be read; llms-full.txt left as it was.")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"\nwrote {OUT} — {len(parts) - 2} pages, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
