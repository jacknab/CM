#!/usr/bin/env node
/**
 * Regenerates shared/usAreaCodes.ts — the US area codes (NPAs) that are currently assigned, taken from Google's libphonenumber
 * metadata as packaged in `libphonenumber-js`. US = the 50 states + DC + the US territories that use the +1 plan
 * (PR, GU, VI, AS, MP); Canadian and Caribbean-nation codes are left out on purpose.
 *
 *   mkdir /tmp/lpn && cd /tmp/lpn && npm init -y && npm i libphonenumber-js
 *   LPN_DIR=/tmp/lpn node scripts/gen-us-area-codes.mjs
 *
 * Re-run it now and then: new overlay area codes are assigned every year or two.
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire((process.env.LPN_DIR || process.cwd()) + "/");
const { parsePhoneNumberFromString } = require("libphonenumber-js/max");
const version = require("libphonenumber-js/package.json").version;

const US_LIKE = new Set(["US", "PR", "GU", "VI", "AS", "MP"]);
// Geographic = an ordinary line: toll-free (800…888), premium (900), personal-number (500, 52X…) and similar ranges are not.
const GEOGRAPHIC = new Set(["FIXED_LINE_OR_MOBILE", "FIXED_LINE", "MOBILE"]);
const codes = [];
const skipped = [];
for (let n = 200; n <= 999; n++) {
  const npa = String(n);
  // Most codes are valid with any exchange; the territories' patterns are exchange-specific, so try every exchange before giving up.
  let p = parsePhoneNumberFromString(`+1${npa}2345678`);
  for (let x = 200; (!p || !p.isValid()) && x <= 999; x++) {
    if (x % 100 === 11) continue;
    p = parsePhoneNumberFromString(`+1${npa}${x}5678`);
  }
  if (!p || !p.isValid() || !US_LIKE.has(p.country)) continue;
  if (GEOGRAPHIC.has(p.getType())) codes.push(npa); else skipped.push(`${npa}(${p.getType()})`);
}
console.log("US but not geographic, left out:", skipped.join(" "));

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "shared", "usAreaCodes.ts");
const rows = [];
for (let i = 0; i < codes.length; i += 12) rows.push("  " + codes.slice(i, i + 12).map((c) => `"${c}"`).join(", ") + ",");
writeFileSync(out, `/**
 * GENERATED by scripts/gen-us-area-codes.mjs from libphonenumber-js ${version} (Google's libphonenumber metadata) — do not edit by hand.
 * The ${codes.length} US area codes (NPAs) currently assigned: the 50 states, DC and the US territories on the +1 plan. Canadian and
 * Caribbean-nation codes are deliberately not in this list.
 */
export const US_AREA_CODES: ReadonlySet<string> = new Set([
${rows.join("\n")}
]);
`);
console.log(`wrote ${codes.length} area codes → ${out}`);
