// ─── Helpers ──────────────────────────────────────────────────────────────────

function storeId(req: Request): number | null {
  const id = parseInt((req.query.storeId ?? req.body?.storeId ?? "") as string);
  return isNaN(id) ? null : id;
}

async function audit(
  sId: number, action: string, entityType: string | null,
  entityId: number | null, req: Request, meta?: Record<string, unknown>
) {
  try {
    await db.insert(payoutAuditLogs).values({
      storeId: sId, action, entityType, entityId,
      userId: (req.session as any)?.userId ?? null,
      metadata: meta ?? null,
    });
  } catch {}
}

function nextCheckNumber(existing: number[]): number {
  if (existing.length === 0) return 1001;
  return Math.max(...existing) + 1;
}

function isStripeAccountAccessError(err: any): boolean {
  const type = String(err?.type ?? "");
  const code = String(err?.code ?? err?.raw?.code ?? "");
  const docUrl = String(err?.doc_url ?? err?.raw?.doc_url ?? "").toLowerCase();
  const msg = String(err?.message ?? err?.raw?.message ?? "").toLowerCase();

  return (
    type === "StripePermissionError" ||
    code === "account_invalid" ||
    docUrl.includes("account-invalid") ||
    msg.includes("does not have access to account")
  );
}

