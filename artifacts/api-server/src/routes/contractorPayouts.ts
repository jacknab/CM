router.post("/contractors/:id/sync-stripe", isAuthenticated, async (req: Request, res: Response): Promise<void> => {
  const id = parseInt(String(req.params.id), 10);
  if (isNaN(id)) { res.status(400).json({ error: "Invalid id" }); return; }

  if (!isStripeConfigured()) {
    res.status(400).json({ error: "Stripe is not configured on this server" }); return;
  }

  try {
    const [contractor] = await db.select().from(contractors).where(eq(contractors.id, id));
    if (!contractor) { res.status(404).json({ error: "Contractor not found" }); return; }

    const sessionStoreId = await resolveSessionStoreId(req);
    if (!sessionStoreId || contractor.storeId !== sessionStoreId) {
      res.status(403).json({ error: "Forbidden" }); return;
    }

    if (!contractor.stripeAccountId) {
      res.status(400).json({ error: "No Stripe account linked to this contractor" }); return;
    }

    const stripe = getStripe();
    let account: Awaited<ReturnType<typeof stripe.accounts.retrieve>>;
    try {
      account = await stripe.accounts.retrieve(contractor.stripeAccountId);
    } catch (err: any) {
      if (isStripeAccountAccessError(err)) {
        await db.update(contractors)
          .set({ onboardingStatus: "restricted", bankVerified: false, updatedAt: new Date() })
          .where(eq(contractors.id, id));

        await audit(contractor.storeId, "stripe_sync_access_lost", "contractor", id, req, {
          stripeAccountId: contractor.stripeAccountId,
          reason: err?.message ?? err?.raw?.message ?? "account access lost",
        });

        res.status(409).json({
          error: "Stripe account access was lost. Start onboarding again to reconnect payouts.",
          code: "STRIPE_ACCOUNT_ACCESS_LOST",
          status: "restricted",
          bankVerified: false,
          stripeAccountId: contractor.stripeAccountId,
        });
        return;
      }
      throw err;
    }

    // Derive + persist via the shared helper (Custom-account aware:
    // transfers capability + requirements + payouts_enabled).
    const synced = await syncContractorAccountStatus(id);
    const onboardingStatus = synced?.onboardingStatus ?? "pending";
    const bankVerified = synced?.bankVerified ?? false;
    const [updated] = await db.select().from(contractors).where(eq(contractors.id, id));

    await audit(contractor.storeId, "stripe_synced", "contractor", id, req, {
      onboardingStatus, bankVerified, requirementsDue: synced?.requirementsDue ?? [],
    });

    // Send verification emails the first time a contractor activates (not a recovery from restricted)
    if (onboardingStatus === "complete" && contractor.onboardingStatus !== "complete" && contractor.onboardingStatus !== "restricted") {
      // Contractor copy — only if they have an email address
      if (contractor.email) {
        sendContractorStripeVerifiedEmail(contractor.email, contractor.firstName)
          .catch((e) => console.warn("[payouts] contractor verified email error:", e?.message));
      }
      // Owner copy — always send (independent of whether contractor has an email)
      sendOwnerContractorVerifiedEmail(contractor.storeId, contractor.firstName, contractor.lastName ?? null)
        .catch((e) => console.warn("[payouts] owner contractor verified email error:", e?.message));
    }

    // Notify the owner the first time this contractor's account transitions TO "restricted"
    // and auto-send a new onboarding invite to the contractor so they can resolve it themselves
    if (onboardingStatus === "restricted" && contractor.onboardingStatus !== "restricted") {
      sendOwnerContractorRestrictedEmail(contractor.storeId, contractor.firstName, contractor.lastName ?? null, contractor.id)
        .catch((e) => console.warn("[payouts] owner contractor restricted email error:", e?.message));
      autoReinviteContractorOnRestriction(contractor, req)
        .catch((e) => console.warn("[payouts] auto-reinvite error:", e?.message));
    }

    // Notify the owner when a previously restricted account recovers back to "complete"
    if (onboardingStatus === "complete" && contractor.onboardingStatus === "restricted") {
      sendOwnerContractorResolvedEmail(contractor.storeId, contractor.firstName, contractor.lastName ?? null, contractor.id)
        .catch((e) => console.warn("[payouts] owner contractor resolved email error:", e?.message));
      // Contractor copy — only if they have an email address
      if (contractor.email) {
        sendContractorResolvedEmail(contractor.email, contractor.firstName)
          .catch((e) => console.warn("[payouts] contractor resolved email error:", e?.message));
      }
    }

    res.json({ status: onboardingStatus, bankVerified, stripeAccountId: contractor.stripeAccountId });
  } catch (err) {
    console.error("[payouts] sync-stripe:", err);
    res.status(500).json({ error: "Failed to sync Stripe status" });
  }
});

