// GET /api/contractor-payouts/ledger?storeId=X&contractorId=X&type=earning|deduction|payout&limit=200&offset=0
router.get("/ledger", isAuthenticated, async (req: Request, res: Response): Promise<void> => {
  const sId = storeId(req);
  if (!sId) { res.status(400).json({ error: "storeId required" }); return; }
  try {
    const contractorIdFilter = req.query.contractorId ? parseInt(req.query.contractorId as string) : null;
    const typeFilter = req.query.type as string | undefined;
    const limit = Math.min(parseInt((req.query.limit as string) ?? "200"), 500);
    const offset = parseInt((req.query.offset as string) ?? "0");

    const conditions = [eq(payoutRuns.storeId, sId)];
    if (contractorIdFilter) conditions.push(eq(payoutRunItems.contractorId, contractorIdFilter));

    const rows = await db
      .select({
        item: payoutRunItems,
        run: {
          id: payoutRuns.id,
          periodStart: payoutRuns.periodStart,
          periodEnd: payoutRuns.periodEnd,
          status: payoutRuns.status,
          createdAt: payoutRuns.createdAt,
        },
        contractor: {
          id: contractors.id,
          firstName: contractors.firstName,
          lastName: contractors.lastName,
        },
      })
      .from(payoutRunItems)
      .leftJoin(payoutRuns, eq(payoutRunItems.payoutRunId, payoutRuns.id))
      .leftJoin(contractors, eq(payoutRunItems.contractorId, contractors.id))
      .where(and(...conditions))
      .orderBy(desc(payoutRuns.createdAt))
      .limit(500);

    type LedgerEntry = {
      id: string; date: string;
      type: "earning" | "deduction" | "adjustment" | "payout";
      category: string; contractorId: number; contractorName: string;
      description: string; amount: number; runningBalance?: number;
    };

    const allEntries: LedgerEntry[] = [];

    for (const { item, run, contractor: c } of rows) {
      if (!c || !run) continue;
      const contractorName = `${c.firstName} ${c.lastName}`;
      const date = run.periodEnd ?? run.periodStart ?? run.createdAt?.toISOString().split("T")[0] ?? "";

      if (!typeFilter || typeFilter === "earning") {
        allEntries.push({
          id: `E-${item.id}`, date,
          type: "earning", category: "Commission Earnings",
          contractorId: item.contractorId, contractorName,
          description: `Period ${run.periodStart} – ${run.periodEnd} · ${item.appointmentCount} appt${item.appointmentCount !== 1 ? "s" : ""}`,
          amount: Number(item.grossAmount),
        });
      }

      const deductions = Array.isArray(item.deductions)
        ? (item.deductions as Array<{ name: string; amount: string }>)
        : [];

      if (!typeFilter || typeFilter === "deduction") {
        for (const ded of deductions) {
          allEntries.push({
            id: `D-${item.id}-${ded.name.replace(/\s+/g, "")}`, date,
            type: "deduction", category: ded.name,
            contractorId: item.contractorId, contractorName,
            description: ded.name,
            amount: -Math.abs(Number(ded.amount)),
          });
        }
      }

      if (item.status === "paid" && item.paidAt && (!typeFilter || typeFilter === "payout")) {
        const paidDate = item.paidAt instanceof Date
          ? item.paidAt.toISOString().split("T")[0]
          : String(item.paidAt).split("T")[0];
        allEntries.push({
          id: `P-${item.id}`, date: paidDate,
          type: "payout", category: "Payout",
          contractorId: item.contractorId, contractorName,
          description: `${(item.payoutMethod ?? "ach").toUpperCase()} payout · Run #${run.id}`,
          amount: -Math.abs(Number(item.netAmount)),
        });
      }
    }

    // Also pull manual adjustments for this store
    const adjConditions = [eq(payoutAdjustments.storeId, sId)];
    if (contractorIdFilter) adjConditions.push(eq(payoutAdjustments.contractorId, contractorIdFilter));

    const adjRows = await db
      .select({
        adj: payoutAdjustments,
        contractor: {
          id: contractors.id,
          firstName: contractors.firstName,
          lastName: contractors.lastName,
        },
      })
      .from(payoutAdjustments)
      .leftJoin(contractors, eq(payoutAdjustments.contractorId, contractors.id))
      .where(and(...adjConditions))
      .orderBy(desc(payoutAdjustments.createdAt));

    if (!typeFilter || typeFilter === "adjustment") {
      for (const { adj, contractor: c } of adjRows) {
        if (!c) continue;
        allEntries.push({
          id: `A-${adj.id}`,
          date: adj.date,
          type: "adjustment",
          category: adj.category,
          contractorId: adj.contractorId,
          contractorName: `${c.firstName} ${c.lastName}`,
          description: adj.description,
          amount: Number(adj.amount),
        });
      }
    }

    allEntries.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());

    // Compute per-contractor running balances (oldest → newest, then reverse)
    const perContractor: Record<number, LedgerEntry[]> = {};
    for (const e of [...allEntries].reverse()) {
      if (!perContractor[e.contractorId]) perContractor[e.contractorId] = [];
      perContractor[e.contractorId].push(e);
    }
    const balanceMap = new Map<string, number>();
    for (const entries of Object.values(perContractor)) {
      let balance = 0;
      for (const e of entries) {
        balance += e.amount;
        balanceMap.set(e.id, balance);
      }
    }
    for (const e of allEntries) e.runningBalance = balanceMap.get(e.id) ?? 0;

    // Summary
    const earns = allEntries.filter(e => e.type === "earning").reduce((s, e) => s + e.amount, 0);
    const deds  = allEntries.filter(e => e.type === "deduction").reduce((s, e) => s + Math.abs(e.amount), 0);
    const pays  = allEntries.filter(e => e.type === "payout").reduce((s, e) => s + Math.abs(e.amount), 0);
    const adjs  = allEntries.filter(e => e.type === "adjustment").reduce((s, e) => s + e.amount, 0);

    const contractorList = await db
      .select({ id: contractors.id, firstName: contractors.firstName, lastName: contractors.lastName })
      .from(contractors)
      .where(and(eq(contractors.storeId, sId), eq(contractors.isActive, true)));

    const page = allEntries.slice(offset, offset + limit);

    res.json({
      entries: page,
      total: allEntries.length,
      summary: { totalEarnings: earns, totalDeductions: deds, totalPayouts: pays, totalAdjustments: adjs, netBalance: earns - deds + adjs - pays },
      contractors: contractorList.map(c => ({ id: c.id, name: `${c.firstName} ${c.lastName}` })),
    });
  } catch (err) {
    console.error("[payouts] ledger:", err);
    res.status(500).json({ error: "Failed to fetch ledger" });
  }
});

