export async function createPayoutRunForPeriod(
  sId: number,
  periodStart: string,
  periodEnd: string,
  opts?: {
    notes?: string | null;
    autoGenerated?: boolean;
    autoApproveAfter?: Date | null;
    createdByUserId?: string | null;
    contractorIds?: number[];
  }
): Promise<{ run: typeof payoutRuns.$inferSelect; items: typeof payoutRunItems.$inferSelect[] } | null> {
  const allContractors = await db
    .select().from(contractors)
    .where(and(eq(contractors.storeId, sId), eq(contractors.isActive, true)));

  const targetContractors = opts?.contractorIds?.length
    ? allContractors.filter(c => opts.contractorIds!.includes(c.id))
    : allContractors;

  if (targetContractors.length === 0) return null;

  const staffIds = targetContractors.map(c => c.staffId).filter(Boolean) as number[];
  const periodStartDate = new Date(periodStart + "T00:00:00Z");
  const periodEndDate   = new Date(periodEnd   + "T23:59:59Z");

  const apptRows = staffIds.length > 0
    ? await db
        .select({
          id:        appointments.id,
          staffId:   appointments.staffId,
          status:    appointments.status,
          totalPaid: appointments.totalPaid,
          tipAmount: appointments.tipAmount,
          serviceId: appointments.serviceId,
        })
        .from(appointments)
        .where(and(
          eq(appointments.storeId, sId),
          eq(appointments.status, "completed"),
          gte(appointments.date, periodStartDate),
          sql`${appointments.date} <= ${periodEndDate}`,
          inArray(appointments.staffId, staffIds),
        ))
    : [];

  const serviceIds = [...new Set(apptRows.map(a => a.serviceId).filter(Boolean) as number[])];
  const servicePriceMap = new Map<number, number>();
  if (serviceIds.length > 0) {
    const svcs = await db
      .select({ id: services.id, price: services.price })
      .from(services)
      .where(inArray(services.id, serviceIds));
    for (const s of svcs) servicePriceMap.set(s.id, Number(s.price ?? 0));
  }

  const apptIds = apptRows.map(a => a.id);
  const addonRevMap = new Map<number, number>();
  if (apptIds.length > 0) {
    const addonRows = await db
      .select({ appointmentId: appointmentAddons.appointmentId, price: addons.price })
      .from(appointmentAddons)
      .leftJoin(addons, eq(appointmentAddons.addonId, addons.id))
      .where(inArray(appointmentAddons.appointmentId, apptIds));
    for (const r of addonRows) {
      addonRevMap.set(r.appointmentId, (addonRevMap.get(r.appointmentId) ?? 0) + Number(r.price ?? 0));
    }
  }

  const deductionRules = await db
    .select().from(payoutDeductionRules)
    .where(and(eq(payoutDeductionRules.storeId, sId), eq(payoutDeductionRules.isActive, true)));

  // Fetch manual adjustments that fall within this pay period (date-range match).
  // Adjustments are keyed by their `date` field so they are included in exactly
  // one run — the one whose period covers that date.
  const periodAdjRows = await db
    .select()
    .from(payoutAdjustments)
    .where(and(
      eq(payoutAdjustments.storeId, sId),
      sql`${payoutAdjustments.date} >= ${periodStart}`,
      sql`${payoutAdjustments.date} <= ${periodEnd}`,
    ));

  // Group adjustments by contractorId for fast lookup
  const adjByContractor = new Map<number, number>();
  for (const adj of periodAdjRows) {
    adjByContractor.set(adj.contractorId, (adjByContractor.get(adj.contractorId) ?? 0) + Number(adj.amount));
  }

  const itemValues: typeof payoutRunItems.$inferInsert[] = [];
  let totalGross = 0, totalDeductions = 0, totalNet = 0;

  for (const c of targetContractors) {
    const myAppts = c.staffId
      ? apptRows.filter(a => a.staffId === c.staffId)
      : [];

    let serviceRevenue = 0, productRevenue = 0, tips = 0;
    for (const a of myAppts) {
      const svcPrice = a.totalPaid
        ? Number(a.totalPaid) - Number(a.tipAmount ?? 0)
        : (servicePriceMap.get(a.serviceId!) ?? 0);
      serviceRevenue += svcPrice;
      productRevenue += addonRevMap.get(a.id) ?? 0;
      tips           += Number(a.tipAmount ?? 0);
    }

    const commRate    = Number(c.commissionRate ?? 0) / 100;
    const prodRate    = Number(c.productCommissionRate ?? 0) / 100;
    const grossAmount = serviceRevenue * commRate + productRevenue * prodRate;

    const applicable = deductionRules.filter(d =>
      d.appliesTo === "all" || (d.appliesTo === "specific" && d.contractorId === c.id)
    );
    const deductionsArr: Array<{ name: string; amount: string; type: string }> = [];
    let dedTotal = 0;
    for (const rule of applicable) {
      const deductionType = rule.type ?? "fixed";
      const dedAmt = deductionType === "percentage"
        ? grossAmount * (Number(rule.amount) / 100)
        : Number(rule.amount);
      deductionsArr.push({ name: rule.name, amount: dedAmt.toFixed(2), type: deductionType });
      dedTotal += dedAmt;
    }

    const effectiveDedTotal = Math.min(grossAmount, dedTotal);
    const scaleFactor = dedTotal > 0 ? effectiveDedTotal / dedTotal : 0;
    const effectiveDeductions = deductionsArr.map(d => ({
      ...d,
      amount: (Number(d.amount) * scaleFactor).toFixed(2),
    }));

    // Manual adjustments for this contractor within the period (+credit / -deduction)
    const adjTotal = adjByContractor.get(c.id) ?? 0;

    const netAmount = grossAmount - effectiveDedTotal + tips + adjTotal;
    totalGross      += grossAmount;
    totalDeductions += effectiveDedTotal;
    totalNet        += netAmount;

    itemValues.push({
      payoutRunId:      0,
      contractorId:     c.id,
      contractorName:   `${c.firstName} ${c.lastName}`,
      appointmentCount: myAppts.length,
      serviceRevenue:   serviceRevenue.toFixed(2),
      productRevenue:   productRevenue.toFixed(2),
      tips:             tips.toFixed(2),
      grossAmount:      grossAmount.toFixed(2),
      deductions:       effectiveDeductions,
      totalDeductions:  effectiveDedTotal.toFixed(2),
      netAmount:        netAmount.toFixed(2),
      payoutMethod:     c.payoutMethod ?? "ach",
      status:           "pending",
    });
  }

  const [run] = await db.insert(payoutRuns).values({
    storeId:          sId,
    periodStart,
    periodEnd,
    status:           "draft",
    totalGross:       totalGross.toFixed(2),
    totalDeductions:  totalDeductions.toFixed(2),
    totalNet:         totalNet.toFixed(2),
    contractorCount:  itemValues.length,
    notes:            opts?.notes ?? null,
    autoGenerated:    opts?.autoGenerated ?? false,
    autoApproveAfter: opts?.autoApproveAfter ?? null,
    createdByUserId:  opts?.createdByUserId ?? null,
  }).returning();

  if (itemValues.length > 0) {
    await db.insert(payoutRunItems).values(
      itemValues.map(v => ({ ...v, payoutRunId: run.id }))
    );
  }

  const items = await db
    .select().from(payoutRunItems)
    .where(eq(payoutRunItems.payoutRunId, run.id));
  return { run, items };
}

export async function approvePayoutRunById(
  runId: number,
  approvedByUserId: string | null
): Promise<{ status: string; errors: string[] }> {
  const [run] = await db.select().from(payoutRuns).where(eq(payoutRuns.id, runId));
  if (!run) throw new Error("Payout run not found");

  const items = await db
    .select({ item: payoutRunItems, contractor: contractors })
    .from(payoutRunItems)
    .leftJoin(contractors, eq(payoutRunItems.contractorId, contractors.id))
    .where(eq(payoutRunItems.payoutRunId, runId));

  const now = new Date();
  await db.update(payoutRuns)
    .set({ status: "processing", approvedByUserId, approvedAt: now, updatedAt: now })
    .where(eq(payoutRuns.id, runId));

  const existingChecks = await db
    .select({ checkNumber: payoutChecks.checkNumber })
    .from(payoutChecks)
    .where(eq(payoutChecks.storeId, run.storeId));
  let nextCheck = nextCheckNumber(existingChecks.map(c => c.checkNumber));

  // Transfers originate FROM the salon's connected Stripe account, not the platform balance.
  // Fetch once here — all items in a run belong to the same store.
  const salonAccount = await getPaymentAccount(run.storeId);
  const salonStripeAccountId = salonAccount?.providerAccountId ?? null;

  let allSucceeded = true;
  const errors: string[] = [];

  // Track contractor IDs that were actually paid during this loop execution.
  // We cannot rely on the pre-fetched item.status (it reflects the snapshot
  // BEFORE processing and is never refreshed in-memory after DB updates).
  const paidContractorIds = new Set<number>();

  for (const { item, contractor: c } of items) {
    if (!c || item.status === "skipped") continue;
    const method = item.payoutMethod ?? c?.payoutMethod ?? "ach";
    try {
      if (method === "check") {
        await db.insert(payoutChecks).values({
          storeId:         run.storeId,
          payoutRunItemId: item.id,
          contractorId:    item.contractorId,
          checkNumber:     nextCheck,
          amount:          item.netAmount,
          payeeName:       `${c.firstName} ${c.lastName}`,
          memo:            `Commission ${run.periodStart} – ${run.periodEnd}`,
          periodStart:     run.periodStart,
          periodEnd:       run.periodEnd,
          printStatus:     "queued",
        });
        await db.update(payoutRunItems)
          .set({ status: "paid", checkNumber: nextCheck, paidAt: now })
          .where(eq(payoutRunItems.id, item.id));
        paidContractorIds.add(c.id); // ← record successful payment
        nextCheck++;
      } else if (method === "instant") {
        // Instant-method contractors are paid at Terminal capture (Uber-like).
        // Mark the batch item skipped so the ledger stays accurate.
        await db.update(payoutRunItems)
          .set({ status: "skipped", failureReason: "Paid via instant transfer at payment capture" })
          .where(eq(payoutRunItems.id, item.id));
        // Instant commissions are already recorded as 'paid' at capture time;
        // do NOT add to paidContractorIds — no reserve to release here.
      } else {
        // ACH — transfer FROM salon's connected account TO contractor's Express account
        const amountCents = Math.round(Math.abs(parseFloat(String(item.netAmount))) * 100);

        if (!isStripeConfigured() || !salonStripeAccountId || !c.stripeAccountId || !c.bankVerified || amountCents < 50) {
          const skipReason = !isStripeConfigured()
            ? "Stripe not configured"
            : !salonStripeAccountId
              ? "Salon has no connected Stripe account"
              : !c.stripeAccountId
                ? "No Stripe account linked"
                : !c.bankVerified
                  ? "Bank account not verified"
                  : "Amount below Stripe minimum ($0.50)";
          await db.update(payoutRunItems)
            .set({ status: "skipped", failureReason: skipReason })
            .where(eq(payoutRunItems.id, item.id));
          // Skipped items don't release reserves — salon owner must fund the account.
        } else {
          const stripe = getStripe();
          // stripeAccount = salon's connected Standard account (funds originate there)
          // destination  = contractor's Express account
          const transfer = await stripe.transfers.create(
            {
              amount:      amountCents,
              currency:    "usd",
              destination: c.stripeAccountId,
              metadata: {
                payout_run_id:      String(runId),
                payout_run_item_id: String(item.id),
                contractor_id:      String(item.contractorId),
                store_id:           String(run.storeId),
                source:             "certxa_payout_run",
              },
            },
            {
              stripeAccount:  salonStripeAccountId,
              idempotencyKey: `payout-run-${runId}-item-${item.id}`,
            }
          );
          console.log(
            `[payoutRun/${runId}] Transferred ${(amountCents / 100).toFixed(2)} salon→contractor ${c.id} (${transfer.id})`
          );
          // Only mark paid + record in paidContractorIds after transfer is confirmed
          await db.update(payoutRunItems)
            .set({ status: "paid", paidAt: now, stripeTransferId: transfer.id })
            .where(eq(payoutRunItems.id, item.id));
          paidContractorIds.add(c.id); // ← record successful payment
        }
      }
    } catch (err: any) {
      allSucceeded = false;
      errors.push(`${c?.firstName ?? "Contractor"} ${c?.lastName ?? ""}: ${err.message}`);
      await db.update(payoutRunItems)
        .set({ status: "failed", failureReason: err.message })
        .where(eq(payoutRunItems.id, item.id));
      // Failed items: leave commission status='pending' so it retries next run.
      // The reserve stays locked — correct behaviour: protects the salon balance.
    }
  }

  const finalStatus = allSucceeded ? "completed" : errors.length === items.length ? "failed" : "completed";
  await db.update(payoutRuns)
    .set({ status: finalStatus, completedAt: now, updatedAt: now })
    .where(eq(payoutRuns.id, runId));

  // ── Release commission reserves for contractors who were actually paid ───────
  // Uses paidContractorIds (built during the loop above) — NOT item.status from
  // the pre-fetch snapshot, which is always "pending" before processing runs.
  if (paidContractorIds.size > 0) {
    try {
      for (const contractorId of paidContractorIds) {
        await pool.query(
          `UPDATE contractor_commissions
           SET status = 'paid', paid_date = $1, updated_at = NOW()
           WHERE store_id = $2 AND contractor_id = $3 AND status = 'pending'
             AND earned_date BETWEEN $4 AND $5`,
          [now, run.storeId, contractorId, run.periodStart, run.periodEnd]
        );
      }
      console.log(
        `[payoutRun/${runId}] Released commission reserves for ${paidContractorIds.size} contractor(s)`
      );
    } catch (commErr: any) {
      // Reserve sync failure must never block the payout result — log and continue.
      console.error("[payoutRun] Commission reserve sync error:", commErr?.message);
    }
  }

  return { status: finalStatus, errors };
}

