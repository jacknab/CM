router.post("/print-batches", isAuthenticated, async (req: Request, res: Response): Promise<void> => {
  const sessionStoreId = await resolveSessionStoreId(req);
  if (!sessionStoreId) { res.status(403).json({ error: "Forbidden" }); return; }
  const userId = (req.session as any)?.userId ?? null;
  const { periodStart, periodEnd, checkCount, totalAmount, envelopeType, checksData, mailerPrinted, isReprint, existingBatchId } = req.body;

  // If this is a reprint of an existing batch, update the reprinted_at timestamp
  if (isReprint && existingBatchId) {
    const [updated] = await db.update(payrollPrintBatches)
      .set({ reprintedAt: new Date() })
      .where(and(eq(payrollPrintBatches.batchId, existingBatchId), eq(payrollPrintBatches.storeId, sessionStoreId)))
      .returning();
    if (!updated) { res.status(404).json({ error: "Batch not found" }); return; }
    res.json(updated);
    return;
  }

  // Generate unique batch ID: {STORE_ABBREV}-{YYYYMMDD}-{SEQ}
  const [storeRow] = await db.select({ name: locations.name }).from(locations).where(eq(locations.id, sessionStoreId)).limit(1);
  const storeName = storeRow?.name ?? "STR";
  const storeAbbrev = storeName.replace(/[^A-Za-z]/g, "").toUpperCase().slice(0, 3).padEnd(3, "X");
  const today = new Date();
  const dateStr = `${today.getFullYear()}${String(today.getMonth() + 1).padStart(2, "0")}${String(today.getDate()).padStart(2, "0")}`;
  const prefix = `${storeAbbrev}-${dateStr}`;
  // Count today's batches for this store to get the next sequence number
  const existing = await db.select({ batchId: payrollPrintBatches.batchId }).from(payrollPrintBatches)
    .where(and(eq(payrollPrintBatches.storeId, sessionStoreId), sql`batch_id LIKE ${prefix + "-%"}`));
  const seq = String(existing.length + 1).padStart(3, "0");
  const batchId = `${prefix}-${seq}`;

  const [batch] = await db.insert(payrollPrintBatches).values({
    storeId: sessionStoreId,
    batchId,
    userId,
    periodStart: periodStart ?? null,
    periodEnd: periodEnd ?? null,
    checkCount: checkCount ?? 0,
    totalAmount: String(totalAmount ?? 0),
    envelopeType: envelopeType ?? "window10",
    checksData: checksData ?? [],
    mailerPrinted: mailerPrinted ?? true,
  }).returning();

  // Mark all included checks as printed
  if (Array.isArray(checksData) && checksData.length > 0) {
    const checkNumbers = checksData.map((c: any) => c.checkNumber);
    // Find checks by store + matching check numbers
    const storeChecks = await db.select({ id: payoutChecks.id, checkNumber: payoutChecks.checkNumber })
      .from(payoutChecks)
      .where(and(eq(payoutChecks.storeId, sessionStoreId), eq(payoutChecks.voidStatus, "active")));
    const idsToMark = storeChecks
      .filter(c => checkNumbers.includes(String(c.checkNumber)))
      .map(c => c.id);
    if (idsToMark.length > 0) {
      await db.update(payoutChecks)
        .set({ printStatus: "printed", printedAt: new Date() })
        .where(and(inArray(payoutChecks.id, idsToMark), eq(payoutChecks.printStatus, "queued")));
    }
  }

  await audit(sessionStoreId, "print_batch_created", "payroll_print_batch", batch.id, req, { batchId, checkCount });
  res.json(batch);
});

export default router;
