// ─── AI extraction ────────────────────────────────────────────────────────────

interface ExtractedService {
  name: string;
  price: number;
  duration: number;
  description?: string;
}

interface ExtractedCategory {
  name: string;
  services: ExtractedService[];
  confidence?: number;        // 0.0-1.0 (from AI matching)
  isAutoGenerated?: boolean;  // true if category was created by AI
}

interface AIMenuResult {
  categories: ExtractedCategory[];
}

// ─── Fuzzy matching helper for fallback category assignment ───────────────────
function calculateSimilarity(str1: string, str2: string): number {
  const s1 = str1.toLowerCase().trim();
  const s2 = str2.toLowerCase().trim();
  if (s1 === s2) return 1.0;
  
  // Simple Levenshtein distance-based similarity
  const longer = s1.length > s2.length ? s1 : s2;
  const shorter = s1.length > s2.length ? s2 : s1;
  
  if (longer.length === 0) return 1.0;
  
  const editDistance = getEditDistance(longer, shorter);
  return (longer.length - editDistance) / longer.length;
}

function getEditDistance(s1: string, s2: string): number {
  const costs: number[] = [];
  for (let j = 0; j <= s2.length; j++) costs[j] = j;
  
  for (let i = 1; i <= s1.length; i++) {
    let nw = i - 1;
    costs[0] = i;
    for (let j = 1; j <= s2.length; j++) {
      const cj = Math.min(
        1 + Math.min(costs[j], costs[j - 1]),
        nw + (s1[i - 1] === s2[j - 1] ? 0 : 1)
      );
      nw = costs[j];
      costs[j] = cj;
    }
  }
  return costs[s2.length] ?? 0;
}

function getOpenAIConfig(): { apiKey: string; baseURL?: string } {
  const directApiKey = process.env.OPENAI_API_KEY?.trim();
  const integrationApiKey = process.env.AI_INTEGRATIONS_OPENAI_API_KEY?.trim();

  if (directApiKey) return { apiKey: directApiKey };
  if (integrationApiKey) {
    const baseURL = process.env.AI_INTEGRATIONS_OPENAI_BASE_URL?.trim();
    return { apiKey: integrationApiKey, ...(baseURL ? { baseURL } : {}) };
  }

  throw new Error("OpenAI API key is not configured");
}

