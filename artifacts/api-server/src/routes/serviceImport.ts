/**
 * Extract services from image files using GPT-4o (vision).
 */
async function extractServicesFromImages(
  imageBuffers: { buffer: Buffer; mimeType: string; originalName: string }[]
): Promise<AIMenuResult> {
  const OpenAI = (await import("openai")).default;
  const openai = new OpenAI(getOpenAIConfig());

  const content: any[] = [
    {
      type: "text",
      text: "Please analyze these nail salon price menu photos and extract all services, categories, prices, and durations. Return structured JSON only.",
    },
  ];

  for (const img of imageBuffers) {
    const base64 = img.buffer.toString("base64");
    const mimeType = img.mimeType.startsWith("image/heic") ? "image/jpeg" : img.mimeType;
    content.push({
      type: "image_url",
      image_url: {
        url: `data:${mimeType};base64,${base64}`,
        detail: "high",
      },
    });
  }

  const completion = await openai.chat.completions.create({
    model: "gpt-4o",
    max_tokens: 4096,
    response_format: { type: "json_object" },
    messages: [
      { role: "system", content: SYSTEM_PROMPT },
      { role: "user", content },
    ],
  });

  return parseAIResponse(completion.choices[0]?.message?.content ?? "");
}

/**
 * Extract services from a PDF file using GPT-5.5 with native PDF understanding.
 * The PDF is uploaded to OpenAI's Files API then referenced in the message.
 */
async function extractServicesFromPDF(
  pdfBuffer: Buffer,
  originalName: string
): Promise<AIMenuResult> {
  const { default: OpenAI, toFile } = await import("openai");
  const openai = new OpenAI(getOpenAIConfig());

  // Upload the PDF to OpenAI Files API so the model can read it natively
  const file = await openai.files.create({
    file: await toFile(pdfBuffer, originalName, { type: "application/pdf" }),
    purpose: "user_data",
  });

  console.log(`[ServiceImport] Uploaded PDF to OpenAI Files API: ${file.id}`);

  let completion: any;
  try {
    completion = await openai.chat.completions.create({
      model: "gpt-5.5",
      max_tokens: 4096,
      response_format: { type: "json_object" },
      messages: [
        { role: "system", content: SYSTEM_PROMPT },
        {
          role: "user",
          content: [
            {
              type: "text",
              text: "Please analyze this nail salon price menu PDF and extract all services, categories, add-ons, variations, and prices. Return structured JSON only.",
            },
            {
              type: "file",
              file: { file_id: file.id },
            } as any,
          ],
        },
      ],
    });
  } finally {
    // Clean up the uploaded file regardless of success/failure
    await openai.files.delete(file.id).catch((e: any) =>
      console.warn(`[ServiceImport] Could not delete OpenAI file ${file.id}:`, e.message)
    );
  }

  return parseAIResponse(completion.choices[0]?.message?.content ?? "");
}

/**
 * Shared JSON response parser — strips markdown fences and validates structure.
 */
function parseAIResponse(raw: string): AIMenuResult {
  const jsonStr = raw
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/\s*```\s*$/i, "")
    .trim();

  const parsed = JSON.parse(jsonStr) as AIMenuResult;

  if (!Array.isArray(parsed.categories)) {
    throw new Error("AI returned unexpected structure — missing categories array");
  }

  return parsed;
}

// ─── Category Management & Intelligent Matching ────────────────────────────────

/**
 * Fetch all existing service categories for a store.
 */
async function getExistingCategories(storeId: number): Promise<string[]> {
  const result = await db
    .select({ name: serviceCategories.name })
    .from(serviceCategories)
    .where(sql`store_id = ${storeId}`)
    .orderBy(sql`sort_order ASC`);
  return result.map(r => r.name);
}

/**
 * Use AI to match a service to the best existing category.
 * Returns category name + confidence score (0.0-1.0).
 * Returns null if no good match found.
 */
async function matchServiceToCategory(
  serviceName: string,
  description: string | undefined,
  existingCategories: string[]
): Promise<{ categoryName: string; confidence: number } | null> {
  if (existingCategories.length === 0) return null;

  const OpenAI = (await import("openai")).default;
  const openai = new OpenAI(getOpenAIConfig());

  const categoryList = existingCategories.join(", ");
  const prompt = `You are a salon service categorization expert. Given a service, pick the BEST matching category.

Service: "${serviceName}"
${description ? `Description: "${description}"` : ""}

Available categories: ${categoryList}

Respond with ONLY valid JSON (no markdown):
{
  "category": "CATEGORY_NAME",
  "confidence": 0.95
}

Confidence should be:
- 1.0 if perfect match
- 0.8-0.99 if very likely
- 0.6-0.79 if reasonable fit
- 0.0-0.59 if poor fit or uncertain`;

  try {
    const completion = await openai.chat.completions.create({
      model: "gpt-4o",
      max_tokens: 100,
      response_format: { type: "json_object" },
      messages: [{ role: "user", content: prompt }],
    });

    const responseText = completion.choices[0]?.message?.content ?? "{}";
    const parsed = JSON.parse(responseText) as { category: string; confidence: number };
    
    // Validate category is in the list
    const isValid = existingCategories.some(c => c.toLowerCase() === parsed.category.toLowerCase());
    if (!isValid) return null;

    return {
      categoryName: parsed.category,
      confidence: Math.min(1.0, Math.max(0.0, parsed.confidence ?? 0)),
    };
  } catch (err: any) {
    console.warn(`[ServiceImport] AI matching failed for "${serviceName}":`, err.message);
    return null;
  }
}

/**
 * Suggest new category names for unmatched services.
 * Returns array of suggested category names (3-5 suggestions).
 */
async function suggestCategoriesForUnmatched(
  unmatched: ExtractedService[]
): Promise<string[]> {
  if (unmatched.length === 0) return [];

  const OpenAI = (await import("openai")).default;
  const openai = new OpenAI(getOpenAIConfig());

  const serviceList = unmatched.map(s => `- ${s.name}${s.description ? ` (${s.description})` : ""}`).join("\n");
  const prompt = `You are a salon service categorization expert. These services don't fit any existing category. Suggest 3-5 logical category names to group them.

Services:
${serviceList}

Respond with ONLY valid JSON (no markdown):
{
  "suggestedCategories": ["Category 1", "Category 2", "Category 3"]
}

Guidelines:
- Use clear, professional names
- Make names broad enough to hold multiple related services
- Avoid generic names like "Other" or "Misc"
- Names should be 1-3 words`;

  try {
    const completion = await openai.chat.completions.create({
      model: "gpt-4o",
      max_tokens: 200,
      response_format: { type: "json_object" },
      messages: [{ role: "user", content: prompt }],
    });

    const responseText = completion.choices[0]?.message?.content ?? "{}";
    const parsed = JSON.parse(responseText) as { suggestedCategories?: string[] };
    
    return (parsed.suggestedCategories ?? []).filter(c => c && typeof c === "string").slice(0, 5);
  } catch (err: any) {
    console.warn(`[ServiceImport] Category suggestion failed:`, err.message);
    return [];
  }
}

/**
 * Main orchestration: enrich AI result with intelligent category matching & auto-creation.
 *
 * Process:
 * 1. Fetch existing store categories
 * 2. For each service: try AI matching (Tier 1) → fuzzy matching (Tier 2)
 * 3. Collect unmatched services
 * 4. If unmatched exist: suggest new categories & create them in DB
 * 5. Return enriched result with all services assigned + confidence scores
 */
async function enrichAIResultWithCategoryMatching(
  aiResult: AIMenuResult,
  storeId: number
): Promise<AIMenuResult> {
  console.log(`[ServiceImport] Enriching AI result with category matching for store ${storeId}…`);

  // Step 1: Get existing categories
  const existingCategoryNames = await getExistingCategories(storeId);
  console.log(`[ServiceImport] Found ${existingCategoryNames.length} existing categories`);

  // Step 2: Flatten all services and attempt matching
  const allServices: Array<ExtractedService & { originalCategory: string }> = [];
  for (const cat of aiResult.categories) {
    for (const svc of cat.services) {
      allServices.push({
        ...svc,
        originalCategory: cat.name,
      });
    }
  }

  const matchedServices: Map<string, { services: ExtractedService[]; confidence: number; isNew: boolean }> = new Map();
  const unmatchedServices: ExtractedService[] = [];

  for (const svc of allServices) {
    let matched = false;

    // Tier 1: Try AI matching
    if (existingCategoryNames.length > 0) {
      const aiMatch = await matchServiceToCategory(svc.name, svc.description, existingCategoryNames);
      if (aiMatch && aiMatch.confidence >= 0.85) {
        console.log(`[ServiceImport] Service "${svc.name}" matched to "${aiMatch.categoryName}" (confidence: ${aiMatch.confidence})`);
        if (!matchedServices.has(aiMatch.categoryName)) {
          matchedServices.set(aiMatch.categoryName, { services: [], confidence: aiMatch.confidence, isNew: false });
        }
        const entry = matchedServices.get(aiMatch.categoryName)!;
        entry.services.push(svc);
        entry.confidence = (entry.confidence + aiMatch.confidence) / 2;
        matched = true;
      }
    }

    // Tier 2: Fallback to fuzzy matching
    if (!matched && existingCategoryNames.length > 0) {
      let bestMatch: { name: string; similarity: number } | null = null;
      for (const catName of existingCategoryNames) {
        const similarity = calculateSimilarity(svc.name, catName);
        if (similarity >= 0.7 && (!bestMatch || similarity > bestMatch.similarity)) {
          bestMatch = { name: catName, similarity };
        }
      }
      if (bestMatch) {
        console.log(`[ServiceImport] Service "${svc.name}" fuzzy-matched to "${bestMatch.name}" (similarity: ${bestMatch.similarity})`);
        if (!matchedServices.has(bestMatch.name)) {
          matchedServices.set(bestMatch.name, { services: [], confidence: bestMatch.similarity, isNew: false });
        }
        matchedServices.get(bestMatch.name)!.services.push(svc);
        matched = true;
      }
    }

    if (!matched) {
      unmatchedServices.push(svc);
      console.log(`[ServiceImport] Service "${svc.name}" has no match, flagged for category creation`);
    }
  }

  // Step 3: Suggest & create new categories for unmatched services
  if (unmatchedServices.length > 0) {
    const suggestedCats = await suggestCategoriesForUnmatched(unmatchedServices);
    console.log(`[ServiceImport] AI suggested ${suggestedCats.length} new categories`);

    for (const catName of suggestedCats) {
      // Create category in DB
      const [newCat] = await db
        .insert(serviceCategories)
        .values({ name: catName, storeId, sortOrder: 999 })
        .returning({ id: serviceCategories.id });

      console.log(`[ServiceImport] Created new category "${catName}" (id: ${newCat.id})`);

      // Assign unmatched services to new category (simple round-robin for demo)
      if (!matchedServices.has(catName)) {
        matchedServices.set(catName, { services: [], confidence: 0.5, isNew: true });
      }
    }

    // Assign remaining unmatched services to new categories
    const newCats = Array.from(matchedServices.entries())
      .filter(([_, entry]) => entry.isNew)
      .map(([name]) => name);

    for (let i = 0; i < unmatchedServices.length; i++) {
      const catIdx = i % newCats.length;
      const catName = newCats[catIdx];
      matchedServices.get(catName)!.services.push(unmatchedServices[i]);
    }
  }

  // Step 4: Build enriched result
  const enrichedResult: AIMenuResult = {
    categories: Array.from(matchedServices.entries()).map(([categoryName, entry]) => ({
      name: categoryName,
      services: entry.services,
      confidence: entry.confidence,
      isAutoGenerated: entry.isNew,
    })),
  };

  console.log(`[ServiceImport] Enrichment complete: ${enrichedResult.categories.length} categories, ${allServices.length} services`);
  return enrichedResult;
}

// ─── Merge helper — combines two AIMenuResult objects, merging same-name categories ──
function mergeMenuResults(base: AIMenuResult, incoming: AIMenuResult): AIMenuResult {
  const merged = { categories: [...base.categories] };
  for (const inCat of incoming.categories) {
    const existing = merged.categories.find(
      c => c.name.toLowerCase() === inCat.name.toLowerCase()
    );
    if (existing) {
      existing.services = [...existing.services, ...inCat.services];
    } else {
      merged.categories.push(inCat);
    }
  }
  return merged;
}

// ─── Async job processor ───────────────────────────────────────────────────────
async function processImportJob(
  jobId: number,
  storeId: number,
  uploadedFiles: { url: string; originalName: string; mimeType: string }[]
) {
  try {
    await updateJob(jobId, { status: "processing" });

    // Download files from their stored URLs for AI processing
    // Files are already stored in R2 / local — fetch them back as buffers
    const allBuffers: { buffer: Buffer; mimeType: string; originalName: string }[] = [];

    for (const file of uploadedFiles) {
      try {
        // If it's a relative /uploads path (local dev), read from disk
        if (file.url.startsWith("/uploads/")) {
          const fs = await import("fs");
          const path = await import("path");
          const diskPath = path.resolve(process.cwd(), "uploads", file.url.slice("/uploads/".length));
          const buffer = fs.readFileSync(diskPath);
          allBuffers.push({ buffer, mimeType: file.mimeType, originalName: file.originalName });
        } else {
          // Fetch from R2 public URL
          const res = await fetch(file.url);
          if (!res.ok) throw new Error(`Failed to fetch ${file.url}: ${res.status}`);
          const arrayBuffer = await res.arrayBuffer();
          allBuffers.push({
            buffer: Buffer.from(arrayBuffer),
            mimeType: file.mimeType,
            originalName: file.originalName,
          });
        }
      } catch (fetchErr: any) {
        console.warn(`[ServiceImport] Could not re-fetch file ${file.url}:`, fetchErr.message);
      }
    }

    if (allBuffers.length === 0) {
      throw new Error("No files could be loaded for AI processing");
    }

    // Route PDFs through GPT-5.5 (native PDF understanding).
    // Images use GPT-4o (vision). If the upload is a mix, run both and merge.
    const pdfBuffers   = allBuffers.filter(f => f.mimeType === "application/pdf");
    const imageBuffers = allBuffers.filter(f => f.mimeType !== "application/pdf");

    let result: AIMenuResult = { categories: [] };

    if (pdfBuffers.length > 0) {
      console.log(`[ServiceImport] Processing ${pdfBuffers.length} PDF(s) with GPT-5.5…`);
      // Process each PDF separately and merge categories
      for (const pdf of pdfBuffers) {
        const pdfResult = await extractServicesFromPDF(pdf.buffer, pdf.originalName);
        result = mergeMenuResults(result, pdfResult);
      }
    }

    if (imageBuffers.length > 0) {
      console.log(`[ServiceImport] Processing ${imageBuffers.length} image(s) with GPT-4o…`);
      const imgResult = await extractServicesFromImages(imageBuffers);
      result = mergeMenuResults(result, imgResult);
    }

    // ─── NEW: Enrich with intelligent category matching ────────────────────────
    console.log(`[ServiceImport] Running category enrichment for store ${storeId}…`);
    result = await enrichAIResultWithCategoryMatching(result, storeId);
    // ─────────────────────────────────────────────────────────────────────────────

    await updateJob(jobId, {
      status: "completed",
      ai_result: JSON.stringify(result),
      completed_at: new Date().toISOString(),
    });

    // Send success email (fire-and-forget)
    const owner = await getStoreOwnerContact(storeId);
    if (owner) {
      const categoryCount = result.categories.length;
      const serviceCount = result.categories.reduce((acc, c) => acc + c.services.length, 0);
      await sendServiceImportSuccessEmail(
        owner.email,
        owner.firstName ?? "there",
        owner.storeName,
        categoryCount,
        serviceCount
      ).catch((e: any) => console.warn("[ServiceImport] Email failed:", e.message));

      await pool
        .query(`UPDATE service_import_jobs SET notified_at = NOW() WHERE id = $1`, [jobId])
        .catch(() => {});
    }
  } catch (err: any) {
    console.error(`[ServiceImport] Job ${jobId} failed:`, err.message);

    // Classify error for friendly messaging
    let friendlyError = err.message ?? "Unknown error";
    if (/json/i.test(friendlyError) || /parse/i.test(friendlyError)) {
      friendlyError =
        "The AI could not read a structured menu from your photos. The images may have been blurry, contained glare, or the prices were not clearly visible. Please try uploading clearer photos.";
    } else if (/api key/i.test(friendlyError)) {
      friendlyError = "AI processing is temporarily unavailable. Please try again later or add your services manually.";
    }

    await updateJob(jobId, {
      status: "failed",
      error_message: friendlyError,
      completed_at: new Date().toISOString(),
    });

    // Send failure email
    const owner = await getStoreOwnerContact(storeId);
    if (owner) {
      await sendServiceImportFailureEmail(
        owner.email,
        owner.firstName ?? "there",
        owner.storeName,
        friendlyError
      ).catch((e: any) => console.warn("[ServiceImport] Failure email failed:", e.message));
    }
  }
}

